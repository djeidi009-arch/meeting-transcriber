/// Выдуманные встречи в настоящем формате папок — для режима `--demo` и скриншотов:
/// личные разговоры из `~/transcripts` в демо не показываются. Аудио здесь нет, его делает приложение.
public enum DemoLibrary {
    private enum When {
        case hoursAgo(Double)          // «сегодня»: от текущего времени, чтобы встреча не оказалась в будущем
        case daysAgo(Int, Int, Int)    // дней назад, часы, минуты
    }

    private struct Meeting {
        let when: When
        let app: String
        var title: String? = nil
        var minutes: Double = 0
        var names: [String: String] = [:]
        var lines: [(speaker: String, text: String)] = []
        var summary: String? = nil
        var summaryError: String? = nil
        var error: String? = nil
    }

    public static func create(at dir: URL) throws {
        let store = MeetingStore(outputDir: dir)
        let library = MeetingLibrary(store: store)
        let calendar = Calendar.current
        let now = Date()

        for meeting in meetings {
            let started: Date
            switch meeting.when {
            case .hoursAgo(let hours):
                started = Date(timeIntervalSinceReferenceDate: ((now.timeIntervalSinceReferenceDate - hours * 3600) / 300).rounded(.down) * 300)
            case .daysAgo(let days, let hour, let minute):
                let day = calendar.date(byAdding: .day, value: -days, to: now) ?? now
                started = calendar.date(bySettingHour: hour, minute: minute, second: 0, of: day) ?? day
            }

            if let error = meeting.error {
                // загруженный файл, которого уже нет на месте
                let folder = try store.createImport(file: URL(fileURLWithPath: "/Users/demo/Movies/\(meeting.app).mp4"), at: started)
                try Data((error + "\n").utf8).write(to: folder.appendingPathComponent("error.txt"))
                continue
            }

            let folder = try store.createMeeting(app: meeting.app, bundleID: "", manual: false, startedAt: started)
            let duration = meeting.minutes * 60
            store.finishMeeting(folder, endedAt: started.addingTimeInterval(duration))

            // реплики растянуты на всю длительность пропорционально длине текста
            let total = Double(meeting.lines.reduce(0) { $0 + $1.text.count })
            var before = 0.0
            let utterances = meeting.lines.map { line -> Utterance in
                let share = Double(line.text.count) / total
                let start = ((2 + before * duration * 0.98) * 100).rounded() / 100
                before += share
                return Utterance(start: start, end: ((start + share * duration * 0.9) * 100).rounded() / 100,
                                 speaker: line.speaker, text: line.text)
            }
            try JSONEncoder().encode(Transcript(utterances: utterances, duration: duration))
                .write(to: folder.appendingPathComponent("transcript.json"))

            if let title = meeting.title { try library.setTitle(title, for: folder) }
            for (label, name) in meeting.names { try library.setSpeakerName(name, label: label, for: folder) }

            guard let item = library.items(queue: .init(running: nil, pending: [])).first(where: { $0.id == folder.lastPathComponent }) else { continue }
            var markdown = MeetingDocument(item: item, transcript: library.transcript(folder),
                                           summaryMarkdown: meeting.summary, user: library.userData(folder)).markdown()
            if let reason = meeting.summaryError {
                markdown = markdown.replacingOccurrences(of: "\nSummary нет.\n", with: "\nSummary не удалось сделать: \(reason). Меню → Повторить summary\n")
            }
            try Data(markdown.utf8).write(to: folder.appendingPathComponent("meeting.md"))
        }
    }

